/// Ramène un caractère au jeu de la police : minuscule -> majuscule, accent retiré, inconnu -> '?'.
fn normalise(c: char) -> char {
    match c {
        'à' | 'â' | 'ä' | 'À' | 'Â' => 'A',
        'é' | 'è' | 'ê' | 'ë' | 'É' | 'È' | 'Ê' => 'E',
        'î' | 'ï' | 'Î' => 'I',
        'ô' | 'ö' | 'Ô' => 'O',
        'ù' | 'û' | 'ü' | 'Ù' => 'U',
        'ç' | 'Ç' => 'C',
        'œ' => 'O',
        c => {
            let m = c.to_ascii_uppercase();
            if (' '..='_').contains(&m) { m } else { '?' }
        }
    }
}

/// Glyphe d'un caractère (8 lignes, bit 0 = pixel de gauche).
pub fn glyphe(c: char) -> &'static [u8; 8] {
    &GLYPHES[(normalise(c) as usize) - 0x20]
}

/// Image de texte R8 : 255 pour la lettre, 128 pour l'ombre portée (+1, +1), 0 ailleurs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TexteRaster {
    largeur: u32,
    hauteur: u32,
    octets: Vec<u8>,
}

impl TexteRaster {
    /// Pas vertical entre deux lignes, en texels (8 de glyphe + 2 d'interligne).
    pub const PAS_LIGNE: u32 = 10;

    /// Trace `lignes` dans une image de `colonnes` x `rangees` caractères (le surplus est coupé).
    pub fn new(lignes: &[String], colonnes: u32, rangees: u32) -> Self {
        let (largeur, hauteur) = (colonnes * 8, rangees * Self::PAS_LIGNE);
        let mut octets = vec![0u8; (largeur * hauteur) as usize];
        let mut pose = |x: u32, y: u32, v: u8, ecrase: bool| {
            if x < largeur && y < hauteur {
                let o = &mut octets[(y * largeur + x) as usize];
                if ecrase || *o == 0 {
                    *o = v;
                }
            }
        };
        for (r, ligne) in lignes.iter().take(rangees as usize).enumerate() {
            for (k, c) in ligne.chars().take(colonnes as usize).enumerate() {
                let g = glyphe(c);
                for (gy, bits) in g.iter().enumerate() {
                    for gx in 0..8u32 {
                        if bits >> gx & 1 == 1 {
                            let (x, y) = (k as u32 * 8 + gx, r as u32 * Self::PAS_LIGNE + gy as u32);
                            pose(x + 1, y + 1, 128, false);
                        }
                    }
                }
            }
        }
        for (r, ligne) in lignes.iter().take(rangees as usize).enumerate() {
            for (k, c) in ligne.chars().take(colonnes as usize).enumerate() {
                let g = glyphe(c);
                for (gy, bits) in g.iter().enumerate() {
                    for gx in 0..8u32 {
                        if bits >> gx & 1 == 1 {
                            pose(
                                k as u32 * 8 + gx,
                                r as u32 * Self::PAS_LIGNE + gy as u32,
                                255,
                                true,
                            );
                        }
                    }
                }
            }
        }
        Self {
            largeur,
            hauteur,
            octets,
        }
    }

    /// Largeur en texels.
    pub fn largeur(&self) -> u32 {
        self.largeur
    }

    /// Hauteur en texels.
    pub fn hauteur(&self) -> u32 {
        self.hauteur
    }

    /// Octets R8, ligne par ligne.
    pub fn octets(&self) -> &[u8] {
        &self.octets
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn les_minuscules_et_accents_se_ramenent_aux_majuscules() {
        assert_eq!(glyphe('a'), glyphe('A'));
        assert_eq!(glyphe('é'), glyphe('E'));
        assert_eq!(glyphe('~'), glyphe('?'));
    }

    #[test]
    fn le_raster_pose_lettre_et_ombre() {
        let r = TexteRaster::new(&["I".to_owned()], 2, 1);
        assert_eq!((r.largeur(), r.hauteur()), (16, TexteRaster::PAS_LIGNE));
        assert!(r.octets().contains(&255) && r.octets().contains(&128));
    }
}
