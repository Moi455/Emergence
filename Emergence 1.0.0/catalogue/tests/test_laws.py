"""T21b: the laws of the body and the mind are data (data/laws.toml). The checker refuses a law without `basis`, a dependency
on a non-objective variable or on a truth forbidden to the tokens, an engine variable with neither law nor reason; the C++
table is generated by addition only (no existing identifier moves)."""
import re
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "tools"))
from schema import Catalogue  # noqa: E402
import gen_cpp  # noqa: E402
import laws  # noqa: E402

GOOD_LAW = '''
[[law]]
id = "zz_test_law"
variables = ["hunger"]
form = "rate"
basis = "design"
unit = "millièmes par heure de jeu"
params = { rate = 1 }
doc_ref = "test"
'''


class TestLaws(unittest.TestCase):
    def problems(self, edit=None, extra_law: str = "", extra_files: dict | None = None) -> list:
        with tempfile.TemporaryDirectory() as t:
            data = Path(t) / "data"
            shutil.copytree(ROOT / "data", data)
            if extra_law:
                with open(data / "laws.toml", "a", encoding="utf-8") as f:
                    f.write(extra_law)
            for name, text in (extra_files or {}).items():
                (data / name).write_text(text, encoding="utf-8")
            if edit:
                edit(data)
            cat = Catalogue.load(data)
            self.assertEqual(cat.load_errors, [])
            return laws.LawChecker(cat).problems()

    @staticmethod
    def sub(data: Path, old: str, new: str, count: int = 1, name: str = "laws.toml") -> None:
        txt = (data / name).read_text(encoding="utf-8")
        assert old in txt, old
        (data / name).write_text(txt.replace(old, new, count), encoding="utf-8")

    def test_shipped_catalogue_has_no_law_problem(self):
        self.assertEqual(laws.LawChecker(Catalogue.load()).problems(), [])

    def test_every_engine_variable_has_a_law_or_a_reason(self):
        cat = Catalogue.load()
        covered = {v for l in cat["law"].values() for v in l.variables}
        for v in cat["variable"].values():
            if "engine" in v.writer:
                self.assertTrue(v.id in covered or v.no_law_reason.strip(), v.id)
                self.assertFalse(v.id in covered and v.no_law_reason, v.id)

    def test_law_without_basis_is_refused(self):
        p = self.problems(extra_law=GOOD_LAW.replace('basis = "design"\n', ""))
        self.assertTrue(any("zz_test_law: basis is required" in x for x in p), p)

    def test_law_with_unknown_basis_is_refused(self):
        p = self.problems(extra_law=GOOD_LAW.replace('"design"', '"whim"'))
        self.assertTrue(any("basis 'whim'" in x for x in p), p)

    def test_a_good_extra_law_passes_except_the_double_owner(self):
        p = self.problems(extra_law=GOOD_LAW)
        self.assertEqual(p, [])   # a variable may be written by several laws (strength: famine and ageing)

    def test_depends_on_a_private_variable_is_refused(self):
        p = self.problems(extra_law=GOOD_LAW + 'depends_on = ["pain"]\n')
        self.assertTrue(any("depends_on 'pain' is private" in x for x in p), p)

    def test_depends_on_a_truth_forbidden_to_tokens_is_refused(self):
        for truth in ("b_truth", "r_true_entity", "m_fact_ref"):
            p = self.problems(extra_law=GOOD_LAW + f'depends_on = ["{truth}"]\n')
            self.assertTrue(any(f"depends_on '{truth}'" in x and "forbidden to the tokens" in x for x in p), (truth, p))
        p = self.problems(extra_law=GOOD_LAW + 'reads = ["b_truth"]\n')
        self.assertTrue(any("reads 'b_truth'" in x for x in p), p)

    def test_objective_dependency_is_accepted(self):
        self.assertEqual(self.problems(extra_law=GOOD_LAW + 'depends_on = ["air_temperature", "blood_volume"]\nreads = ["pain"]\n'), [])

    def test_unknown_dependency_and_variable(self):
        p = self.problems(extra_law=GOOD_LAW + 'depends_on = ["no_such_variable"]\n')
        self.assertTrue(any("unknown variable 'no_such_variable'" in x for x in p), p)
        p = self.problems(extra_law=GOOD_LAW.replace('["hunger"]', '["no_such_variable"]'))
        self.assertTrue(any("unknown variable" in x for x in p), p)

    def test_engine_variable_without_law_nor_reason_is_refused(self):
        new_var = ('[[variable]]\nid = "zz_orphan"\nlabel_fr = "variable factice"\nholder = "mind_dynamic"\n'
                   'scale = "unipolar10"\nwriter = ["engine"]\nvisibility = "private"\n')
        p = self.problems(extra_files={"zz_orphan.toml": new_var})
        self.assertTrue(any("variable zz_orphan: written by the engine, needs a [[law]]" in x for x in p), p)
        p = self.problems(extra_files={"zz_orphan.toml": new_var + 'no_law_reason = "test: nothing drives it"\n'})
        self.assertEqual(p, [])

    def add_reason(self, d: Path, var: str) -> None:
        for f in sorted(d.glob("*.toml")):
            txt = f.read_text(encoding="utf-8")
            new = re.sub(r'(\{ id = "%s",[^\n]*?) \}' % var, r'\1, no_law_reason = "x" }', txt, count=1)
            if new != txt:
                f.write_text(new, encoding="utf-8")
                return
        raise AssertionError(var)

    def test_unknown_variable_in_a_law_is_refused(self):
        p = self.problems(edit=lambda d: self.sub(d, 'variables = ["hunger"]', 'variables = ["hunger", "zz_x"]'))
        self.assertTrue(any("zz_x" in x for x in p), p)

    def test_variable_with_both_law_and_reason_is_refused(self):
        p = self.problems(edit=lambda d: self.add_reason(d, "hunger"))
        self.assertTrue(any("variable hunger: has both a law" in x for x in p), p)

    def test_no_law_reason_on_a_non_engine_variable_is_refused(self):
        p = self.problems(edit=lambda d: self.add_reason(d, "resilience"))
        self.assertTrue(any("resilience: no_law_reason on a variable the engine does not write" in x for x in p), p)

    def test_params_must_be_integers_and_by_exertion_complete(self):
        p = self.problems(extra_law=GOOD_LAW.replace("rate = 1", "rate = 1.5"))
        self.assertTrue(any("must be an integer" in x for x in p), p)
        p = self.problems(extra_law=GOOD_LAW + "by_exertion = [1, 2, 3]\n")
        self.assertTrue(any("by_exertion needs 6 values" in x for x in p), p)
        p = self.problems(extra_law=GOOD_LAW.replace('form = "rate"', 'form = "magic"'))
        self.assertTrue(any("form 'magic'" in x for x in p), p)
        p = self.problems(extra_law=GOOD_LAW.replace("rate = 1", "tau_real_s = 0"))
        self.assertTrue(any("duration 'tau_real_s' must be > 0" in x for x in p), p)

    def test_duplicate_law_id_is_refused(self):
        with tempfile.TemporaryDirectory() as t:
            data = Path(t) / "data"
            shutil.copytree(ROOT / "data", data)
            with open(data / "laws.toml", "a", encoding="utf-8") as f:
                f.write(GOOD_LAW.replace("zz_test_law", "hunger_rise"))
            self.assertTrue(any("duplicate law id 'hunger_rise'" in x for x in Catalogue.load(data).load_errors))


class TestLawGeneration(unittest.TestCase):
    def build(self, tmp: Path, extra: str = "") -> dict:
        data = tmp / "data"
        shutil.copytree(gen_cpp.ROOT / "data", data)
        if extra:
            with open(data / "laws.toml", "a", encoding="utf-8") as f:
                f.write(extra)
        cat = Catalogue.load(data)
        return gen_cpp.build(cat, gen_cpp.Orders(cat, strict=False, var_registry=gen_cpp.VarRegistry(), vocab_registry=gen_cpp.VocabRegistry()))

    def test_laws_table_is_shipped_and_typed(self):
        text = gen_cpp.build(Catalogue.load())[gen_cpp.LAWS_OUT]
        self.assertEqual(gen_cpp.LAWS_OUT.read_text(encoding="utf-8"), text)
        self.assertIn("kLaws = {{", text)
        self.assertIn('{"hunger_rise", LawForm::rate, LawBasis::design,', text)
        self.assertIn("kLawExertion_hunger_rise = {2000ll, 3500ll, 4500ll, 9000ll, 14000ll, 11000ll}", text)

    def test_adding_a_law_moves_no_existing_identifier(self):
        with tempfile.TemporaryDirectory() as t:
            base = self.build(Path(t) / "a")
            new = self.build(Path(t) / "b", extra=GOOD_LAW)
        for path, text in base.items():
            if path != gen_cpp.LAWS_OUT:
                self.assertEqual(new[path], text, f"{path.name} moved when a law was added")
        self.assertIn("zz_test_law", new[gen_cpp.LAWS_OUT])
        self.assertNotEqual(base[gen_cpp.LAWS_OUT], new[gen_cpp.LAWS_OUT])


if __name__ == "__main__":
    unittest.main()
