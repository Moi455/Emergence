"""forgetting.py - the law of forgetting (docs/14 7.5, task T05): its checker and its Python oracle.

    ForgettingChecker(cat).problems()   # what check.py and gen_cpp.py enforce on data/forgetting.toml
    ForgettingOracle(cat)               # score / protected / victim, integer arithmetic only, the reference of the C++ parity

The law never depends on the truth of the world: a score may not read b_truth, b_origin_fact, m_fact_ref, r_true_entity
(nor any variable of the `id` scale, which is an objective identifier). A recency counts in seasons (D30: 1 season =
1 h 45 real = 100 800 game seconds) and halves at each half-life, linearly in between. The C++ side
(`gen::forgetting_score`, generated by gen_cpp.py) must give the same integers: the parity test draws PARITY_RECORDS
records with the same generator (SplitMix64) and compares a hash of every (score, protected).
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from schema import Catalogue  # noqa: E402

SEASON_SECONDS = 6_300 * 16   # 1 h 45 real (6 300 s) x 16 game seconds per real second (WorldClock)
FORBIDDEN_VARS = ("b_truth", "b_origin_fact", "m_fact_ref", "r_true_entity")
SCORE_SCALES = ("bipolar10", "unipolar10", "qty", "ratio", "bool", "time")   # numeric variables only
KINDS = ("value", "recency")
MAX_WEIGHT = 10_000   # a bool of 10 points weighs 10 000
# Normalisation: the largest contribution of one term (|weight| x the span of its variable) is a whole number of
# "points" of POINT units, 1 to MAX_POINTS points, so that terms of different scales are comparable.
POINT = 1000
MAX_POINTS = 10
SPAN = {"unipolar10": 100, "bipolar10": 100, "ratio": 1000, "bool": 1}   # stored span of a value (qty: its cap; recency: 100)
INT32_MIN, INT32_MAX = -(1 << 31), (1 << 31) - 1

# Parity: draws of a variable, by scale (low, high inclusive); a time is drawn around `PARITY_NOW`.
PARITY_RECORDS = 10_000
PARITY_NOW = 30 * SEASON_SECONDS
DRAW_RANGE = {"bool": (0, 1), "unipolar10": (0, 100), "bipolar10": (-100, 100), "ratio": (0, 1000), "qty": (0, 300)}
M64 = (1 << 64) - 1


def recency(age: int, half_life: int) -> int:
    """100 for a brand-new event, halving every `half_life` seconds (linear in between), 0 after ten half-lives."""
    age = max(age, 0)
    whole, rest = divmod(age, half_life)
    if whole >= 10:
        return 0
    r = 1000 >> whole
    r -= r * rest // (2 * half_life)
    return r // 10


def clamp32(x: int) -> int:
    return max(INT32_MIN, min(INT32_MAX, x))


def record_components(cat: Catalogue) -> list:
    """The record components an NPC holds, in catalogue order (these are the kinds of record)."""
    return [c.id for c in cat["component"].values() if c.part_of and c.holder == "agent"]


class ForgettingChecker:
    def __init__(self, cat: Catalogue):
        self.cat = cat

    def problems(self) -> list:
        cat, p = self.cat, []
        laws = cat["forgetting"]
        records = record_components(cat)
        for rec in records:
            if rec not in laws:
                p.append(f"forgetting: record '{rec}' has no [[forgetting]] law")
        for rid, law in laws.items():
            if law.record != rid or rid not in records:
                p.append(f"forgetting {rid}: 'record' must name a record component held by an agent (part_of)")
                continue
            p += self._law(law)
        return p

    def _var(self, law, name: str, what: str):
        """The variable `name` of the record of `law`, or None (the problem is then returned by problem())."""
        v = self.cat["variable"].get(name)
        if v is None:
            return None, f"forgetting {law.record}: {what} '{name}' is not a variable"
        if name in FORBIDDEN_VARS or v.scale == "id":
            return None, f"forgetting {law.record}: {what} '{name}' reads the truth of the world (forgetting never depends on it)"
        if v.holder != law.record:
            return None, f"forgetting {law.record}: {what} '{name}' belongs to '{v.holder}', not to the record"
        return v, ""

    def _law(self, law) -> list:
        p = []
        if not self.cat["component"][law.record].max_count:
            p.append(f"forgetting {law.record}: the component has no max_count (the capacity is fixed in v1)")
        for name in law.protect:
            v, err = self._var(law, name, "protect")
            if err:
                p.append(err)
            elif v.scale != "bool":
                p.append(f"forgetting {law.record}: protect '{name}' must be a bool")
        if not law.score:
            p.append(f"forgetting {law.record}: empty score")
        seen = set()
        for i, t in enumerate(law.score):
            where = f"score[{i}]"
            unknown = set(t) - {"var", "weight", "cap", "kind", "half_life_seasons"}
            if unknown:
                p.append(f"forgetting {law.record}: {where} unknown fields {sorted(unknown)}")
            name = t.get("var", "")
            v, err = self._var(law, name, where)
            if err:
                p.append(err)
                continue
            if name in seen:
                p.append(f"forgetting {law.record}: {where} reads '{name}' twice")
            seen.add(name)
            if v.scale not in SCORE_SCALES:
                p.append(f"forgetting {law.record}: {where} '{name}' has scale {v.scale}, not a number")
            w = t.get("weight")
            if not isinstance(w, int) or isinstance(w, bool) or w == 0 or abs(w) > MAX_WEIGHT:
                p.append(f"forgetting {law.record}: {where} weight must be a non-zero integer, |w| <= {MAX_WEIGHT}")
            kind = t.get("kind", "value")
            if kind not in KINDS:
                p.append(f"forgetting {law.record}: {where} kind '{kind}' not in {KINDS}")
            elif kind == "recency":
                h = t.get("half_life_seasons")
                if v.scale != "time":
                    p.append(f"forgetting {law.record}: {where} recency needs a time variable")
                if not isinstance(h, int) or isinstance(h, bool) or h <= 0:
                    p.append(f"forgetting {law.record}: {where} recency needs half_life_seasons > 0")
                if "cap" in t:
                    p.append(f"forgetting {law.record}: {where} a recency has no cap")
            else:
                cap = t.get("cap")
                if v.scale == "time":
                    p.append(f"forgetting {law.record}: {where} a time is read with kind = \"recency\"")
                if "half_life_seasons" in t:
                    p.append(f"forgetting {law.record}: {where} half_life_seasons only with kind = \"recency\"")
                if cap is not None and (not isinstance(cap, int) or isinstance(cap, bool) or cap <= 0):
                    p.append(f"forgetting {law.record}: {where} cap must be a positive integer")
                if v.scale == "qty" and cap is None:
                    p.append(f"forgetting {law.record}: {where} a qty ('{name}') needs a cap (terms must be comparable)")
            amp = self.amplitude(t, v)
            if amp is not None and isinstance(w, int) and not isinstance(w, bool) and w != 0:
                if amp % POINT or not POINT <= amp <= MAX_POINTS * POINT:
                    p.append(f"forgetting {law.record}: {where} '{name}' weighs {amp} at most, not a whole 1..{MAX_POINTS} "
                             f"points of {POINT} (weight x span; see data/forgetting.toml)")
        return p


    @staticmethod
    def amplitude(t: dict, v):
        """The largest |contribution| of a term, or None when it cannot be told (malformed term, reported elsewhere)."""
        w = t.get("weight")
        if not isinstance(w, int) or isinstance(w, bool):
            return None
        if t.get("kind", "value") == "recency":
            return abs(w) * 100
        if v.scale == "qty":
            cap = t.get("cap")
            return abs(w) * cap if isinstance(cap, int) and not isinstance(cap, bool) else None
        span = SPAN.get(v.scale)
        return None if span is None else abs(w) * span


class ForgettingLaw:
    """The law of one kind of record. A record is a dict {variable: int} (a missing variable reads 0)."""

    def __init__(self, entry):
        self.record, self.protect, self.terms = entry.record, list(entry.protect), list(entry.score)

    @property
    def fields(self) -> list:
        """The variables the law reads, protect first, then the score, each once: the order of the parity draws."""
        out = []
        for name in self.protect + [t["var"] for t in self.terms]:
            if name not in out:
                out.append(name)
        return out

    def is_protected(self, rec: dict) -> bool:
        return any(rec.get(n, 0) != 0 for n in self.protect)

    def score(self, rec: dict, now: int = 0) -> int:
        total = 0
        for t in self.terms:
            v = int(rec.get(t["var"], 0))
            if t.get("kind", "value") == "recency":
                half = t["half_life_seasons"] * SEASON_SECONDS
                total += t["weight"] * recency(now - v, half)
            else:
                if "cap" in t:
                    v = min(v, t["cap"])
                total += t["weight"] * v
        return clamp32(total)


class ForgettingOracle:
    def __init__(self, cat: Catalogue):
        self.cat = cat
        self.kinds = [r for r in cat["forgetting"]]                 # the order of data/forgetting.toml = the C++ Kind enum
        self.laws = {r: ForgettingLaw(e) for r, e in cat["forgetting"].items()}

    def score(self, kind: str, rec: dict, now: int = 0) -> int:
        return self.laws[kind].score(rec, now)

    def is_protected(self, kind: str, rec: dict) -> bool:
        return self.laws[kind].is_protected(rec)

    def victim(self, kind: str, entries: list, now: int = 0):
        """entries = [(serial, record)] of a full store: the serial to forget (lowest score, ties: the oldest serial).
        A protected record is spared while an unprotected one exists; when EVERY record is protected the worst of them
        goes (same law, same tie) and the pool counts it (evicted_protected): an NPC never stops forming memories.
        None only for an empty store."""
        law = self.laws[kind]
        best = {False: None, True: None}                 # by "protected": the best victim of each class
        for serial, rec in entries:
            prot = law.is_protected(rec)
            key = (law.score(rec, now), serial)
            if best[prot] is None or key < best[prot][0]:
                best[prot] = (key, serial)
        pick = best[False] or best[True]
        return None if pick is None else pick[1]

    # ---- parity with the C++ generated code ----------------------------------------------------------------------
    def draw_record(self, kind: str, rng: "SplitMix64", now: int = PARITY_NOW) -> dict:
        rec = {}
        for name in self.laws[kind].fields:
            scale = self.cat["variable"][name].scale
            u = rng.next()
            if scale == "time":
                rec[name] = 0 if u % 17 == 0 else now + SEASON_SECONDS - u % (14 * SEASON_SECONDS)
            else:
                lo, hi = DRAW_RANGE[scale]
                rec[name] = lo + u % (hi - lo + 1)
        return rec

    def parity_hash(self, n: int = PARITY_RECORDS, seed: int = 0xE5CA1AB1E) -> int:
        """FNV-1a 64 over (score as 4 little-endian bytes, protected as 1 byte) of n records, kind = index mod kinds."""
        rng, h = SplitMix64(seed), 0xcbf29ce484222325
        for i in range(n):
            kind = self.kinds[i % len(self.kinds)]
            rec = self.draw_record(kind, rng)
            data = (self.score(kind, rec, PARITY_NOW) & 0xFFFFFFFF).to_bytes(4, "little") + bytes([self.is_protected(kind, rec)])
            for b in data:
                h = ((h ^ b) * 0x100000001b3) & M64
        return h


class SplitMix64:
    def __init__(self, seed: int):
        self.s = seed & M64

    def next(self) -> int:
        self.s = (self.s + 0x9E3779B97F4A7C15) & M64
        z = self.s
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
        return z ^ (z >> 31)
