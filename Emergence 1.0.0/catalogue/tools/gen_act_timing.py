#!/usr/bin/env python3
"""T22: the timing table of the gestures (engine/act/gesture_timing.*), generated from catalogue/data/actions.toml.
Writes engine/act/generated/emergence/act/gesture_timing_gen.h: for each of the gestures (in the order of
social::gen::kGestureNames, i.e. sorted by id) natural_end, cadence_ms and productive, the chosen duration levels
(game seconds) and the nutrition / hydration of the food items. Nothing else is read, no identifier moves: this
generator only adds a header and does not touch gen_cpp.py.

    python3 catalogue/tools/gen_act_timing.py          # write
    python3 catalogue/tools/gen_act_timing.py --check  # exit 1 when the header is stale
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT.parent / "engine" / "act" / "generated" / "emergence" / "act" / "gesture_timing_gen.h"


def load(name: str) -> dict:
    return tomllib.loads((DATA / name).read_text(encoding="utf-8"))


def build() -> str:
    actions = load("actions.toml")
    gestures = sorted(actions["action"], key=lambda a: a["id"])
    levels = actions["duration_level"]
    lines = [
        "// GENERATED by catalogue/tools/gen_act_timing.py from catalogue/data/actions.toml and items_food.toml - do not edit (T22).",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace em::act::timing_gen {",
        "",
        "// One row per gesture, in the order of social::gen::kGestureNames (sorted by id).",
        "struct GestureTimingRow {",
        "  std::string_view id;",
        "  bool natural_end;           // the gesture ends by itself (an arrival, a blow, a sip)",
        "  bool productive;            // work on matter: kTaskCompression applies (P37)",
        "  std::uint16_t cadence_ms;   // real milliseconds per engine cycle",
        "};",
        f"inline constexpr std::array<GestureTimingRow, {len(gestures)}> kGestureTiming = {{{{",
    ]
    for a in gestures:
        lines.append('  {"%s", %s, %s, %d},' % (a["id"], str(bool(a.get("natural_end", False))).lower(),
                                                 str(bool(a.get("productive", False))).lower(), int(a["cadence_ms"])))
    lines += ["}};", "",
              "// Chosen durations (duration head): game seconds, in the order of the values brief, a_while, long.",
              "struct DurationLevelRow { std::string_view id; std::int64_t game_s; };",
              f"inline constexpr std::array<DurationLevelRow, {len(levels)}> kDurationLevels = {{{{"]
    for lv in levels:
        lines.append('  {"%s", %d},' % (lv["id"], int(lv["game_s"])))
    lines += ["}};", ""]
    foods = []
    for fname in sorted(p.name for p in DATA.glob("items_*.toml")):
        for it in load(fname).get("item_type", []):
            props = it.get("properties", {})
            n, h = int(props.get("nutrition", 0) or 0), int(props.get("hydration", 0) or 0)
            if n or h:
                foods.append((it["id"], n, h))
    lines += ["// Items that feed or quench (properties nutrition and hydration, scale 0..10).",
              "struct IngestibleRow { std::string_view id; std::int32_t nutrition, hydration; };",
              f"inline constexpr std::array<IngestibleRow, {len(foods)}> kIngestibles = {{{{"]
    for i, n, h in foods:
        lines.append('  {"%s", %d, %d},' % (i, n, h))
    lines += ["}};", "", "}  // namespace em::act::timing_gen", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    text = build()
    if "--check" in args:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.stderr.write("stale: gesture_timing_gen.h -> run python3 catalogue/tools/gen_act_timing.py\n")
            return 1
        print("gesture timing table up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("écrit " + OUT.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
