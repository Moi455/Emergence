#!/usr/bin/env python3
"""T18: the tables of the laws of matter (engine/act/laws), generated from catalogue/ (matter.toml, materials,
forms.toml, items_*.toml). Writes engine/act/generated/emergence/act/matter_gen.h and the append-only registry
catalogue/generated/matter_registry.json (ids of materials, forms, processes and item sorts never move).

    python3 catalogue/tools/gen_matter.py          # write
    python3 catalogue/tools/gen_matter.py --check  # exit 1 when the header or the registry is stale

gen_cpp.py is not touched: this generator only reads the same catalogue and reuses its append-only registry classes.
Everything is integer (grams, millimetres, per-mille): the C++ side has no floating point.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "tools"))
import gen_cpp  # noqa: E402
from gen_cpp import AppendOnlyFile, StableOrder, cpp_str  # noqa: E402

OUT = ROOT.parent / "engine" / "act" / "generated" / "emergence" / "act" / "matter_gen.h"
REGISTRY = ROOT / "generated" / "matter_registry.json"
VOCAB = ROOT / "generated" / "vocab_registry.json"   # kKinds: the canonical `sort` of an entity is the index of its id here
SCHEMA = "matter-registry-1"

# What a form gives (forms.toml `gives`) that the contact laws read, as a bit mask. Append-only.
AFFORDANCE_BITS = ("edge", "point", "handle", "abrasiveness", "binds", "reach")

COHESION = {"": 0, "natural": 0, "built": 1, "loose": 2, "fluid": 3}
TILLABLE_CATEGORIES = ("soil",)   # materials.csv categories the process till (sol cultivable) can turn
CLOCKS = ("real", "game", "calendar", "life")   # append-only; a new clock in the catalogue must be added here


class MatterRegistry(AppendOnlyFile):
    SCHEMA, LISTS = SCHEMA, ("materials", "forms", "processes", "items")

    def __init__(self, path: Path = REGISTRY):
        super().__init__(path)


def camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def round_half_up(num: int, den: int) -> int:
    return (2 * num + den) // (2 * den)


def build() -> dict:
    cat = gen_cpp.Catalogue.load()
    problems = cat.validate()
    if problems:
        raise SystemExit("catalogue does not validate:\n" + "\n".join(problems))
    kinds = [e["name"] for e in json.loads(VOCAB.read_text(encoding="utf-8"))["kinds"]]
    kind_ix = {n: i for i, n in enumerate(kinds)}
    live = {
        "materials": list(cat["material"]),
        "forms": list(cat["form"]),
        "processes": list(cat["process"]),
        "items": list(cat["item_type"]),
    }
    reg = MatterRegistry().updated(live, hints={k: v for k, v in live.items()})
    order = {k: StableOrder(reg.names(k), live[k]) for k in live}
    mat_ix = {n: i for i, n in enumerate(order["materials"].names)}
    form_ix = {n: i for i, n in enumerate(order["forms"].names)}
    proc_ix = {n: i for i, n in enumerate(order["processes"].names)}
    L: list[str] = []
    e = L.append
    e("// GENERATED by catalogue/tools/gen_matter.py from catalogue/ - do not edit (T18, laws of matter).")
    e("// Materials, forms, processes and item sorts, with the ids of catalogue/generated/matter_registry.json (append-only).")
    e("// Integers only: grams, millimetres, per-mille. Item sort = registry index + 1 (0 = no sort).")
    e("#pragma once")
    e("#include <array>")
    e("#include <cstdint>")
    e("#include <string_view>")
    e("")
    e("namespace em::act::matter {")
    e("")
    e("inline constexpr std::uint16_t kNoMatter = 0xFFFF;")
    e("enum class Cohesion : std::uint8_t { natural, built, loose, fluid };")
    e("enum class Clock : std::uint8_t { " + ", ".join(CLOCKS) + " };")
    for i, b in enumerate(AFFORDANCE_BITS):
        e(f"inline constexpr std::uint8_t kForm{camel(b)} = {1 << i};")
    e(f"inline constexpr std::uint8_t kFormBlunt = {1 << len(AFFORDANCE_BITS)};   // forms whose rule names the affordance impacts")
    e("")
    # Materials
    ms = order["materials"].slots
    e("struct MaterialRow {")
    e("  std::string_view name;")
    e("  std::string_view category;     // soil, rock, wood, metal, ...")
    e("  std::int32_t csv_class;        // class of engine/data/materials.csv, -1 when proposed (not yet a voxel class)")
    e("  std::int32_t density_kg_m3;")
    e("  std::int16_t hardness;         // 0..100")
    e("  std::int16_t toughness;        // 0..100; the catalogue leaves it blank for some: then the hardness")
    e("  Cohesion cohesion;")
    e("  bool tillable;                 // category the process till can turn")
    e("  bool live;")
    e("};")
    e(f"inline constexpr std::array<MaterialRow, {len(ms)}> kMaterials = {{{{")
    for s in ms:
        m = cat["material"].get(s.name)
        if m is None:
            e(f'  {{"", "", -1, 0, 0, 0, Cohesion::natural, false, false}},   // retired {s.index}')
            continue
        hard = int(m.hardness)
        tough = int(m.toughness) if m.toughness >= 0 else hard
        coh = ["natural", "built", "loose", "fluid"][COHESION[m.cohesion]]
        e(f'  {{{cpp_str(m.id)}, {cpp_str(m.category)}, {int(m.num)}, {int(round(m.density_kg_m3))}, {hard}, {tough}, Cohesion::{coh}, {'true' if m.category in TILLABLE_CATEGORIES else 'false'}, true}},')
    e("}};")
    e("")
    # Forms
    fs = order["forms"].slots
    e("struct FormRow { std::string_view name; std::uint8_t flags; bool live; };")
    e(f"inline constexpr std::array<FormRow, {len(fs)}> kForms = {{{{")
    for s in fs:
        f = cat["form"].get(s.name)
        if f is None:
            e('  {"", 0, false},')
            continue
        bits = 0
        for g in f.gives:
            if g in AFFORDANCE_BITS:
                bits |= 1 << AFFORDANCE_BITS.index(g)
        if "impacts" in f.rule:   # a form whose rule says it concentrates mass for impacts (forms.toml)
            bits |= 1 << len(AFFORDANCE_BITS)
        e(f'  {{{cpp_str(f.id)}, {bits}, true}},')
    e("}};")
    e("")
    # Processes
    ps = order["processes"].slots
    e("enum class ProcessId : std::uint16_t {")
    for s in ps:
        e(f"  {camel(s.name) if s.live else 'Retired' + str(s.index)},")
    e("  kCount")
    e("};")
    e("struct ProcessRow {")
    e("  std::string_view name;")
    e("  Clock clock;")
    e("  std::int32_t nominal_game_s;")
    e("  std::uint8_t n_consumes, n_produces;")
    e("  std::array<std::uint16_t, 4> consumes;   // MaterialRow indices")
    e("  std::array<std::uint16_t, 4> produces;")
    e("  bool live;")
    e("};")
    e(f"inline constexpr std::array<ProcessRow, {len(ps)}> kProcesses = {{{{")
    for s in ps:
        p = cat["process"].get(s.name)
        if p is None:
            e('  {"", Clock::game, 0, 0, 0, {}, {}, false},')
            continue
        assert p.clock in CLOCKS, p.clock
        assert len(p.consumes) <= 4 and len(p.produces) <= 4, p.id

        def arr(names):
            ids = [mat_ix[n] for n in names] + [0xFFFF] * (4 - len(names))
            return "{" + ", ".join(str(i) for i in ids) + "}"
        e(f'  {{{cpp_str(p.id)}, Clock::{p.clock}, {int(p.nominal_game_s)}, {len(p.consumes)}, {len(p.produces)}, '
          f'{arr(p.consumes)}, {arr(p.produces)}, true}},')
    e("}};")
    e("")
    # Items
    items = order["items"].slots
    parts_flat: list[tuple[int, int]] = []
    made_flat: list[int] = []
    rows = []
    for s in items:
        it = cat["item_type"].get(s.name)
        if it is None:
            rows.append(None)
            continue
        p0 = len(parts_flat)
        for part in it.parts:
            fm, mt = part.split(":")
            parts_flat.append((form_ix[fm], mat_ix[mt]))
        m0 = len(made_flat)
        for pr in it.made_by:
            if pr in proc_ix:
                made_flat.append(proc_ix[pr])
        mass_g = round_half_up(int(round(float(it.mass_kg) * 1000 * 1000)), 1000)
        rows.append((it, p0, len(it.parts), m0, len(made_flat) - m0, mass_g, kind_ix.get(it.id, 0)))
    e("struct PartRow { std::uint16_t form, material; };")
    e(f"inline constexpr std::array<PartRow, {max(1, len(parts_flat))}> kItemParts = {{{{")
    for f, m in parts_flat or [(0, 0)]:
        e(f"  {{{f}, {m}}},")
    e("}};")
    e(f"inline constexpr std::array<std::uint16_t, {max(1, len(made_flat))}> kItemMadeBy = {{{{")
    e("  " + ", ".join(str(x) for x in (made_flat or [0])))
    e("}};")
    e("struct ItemRow {")
    e("  std::string_view name;")
    e("  std::int32_t mass_g;")
    e("  std::uint16_t sort;                   // index of the id in kKinds (vocab_registry.json); 0 when the id is not a kind")
    e("  std::uint16_t parts_at, parts_n;      // kItemParts")
    e("  std::uint16_t made_by_at, made_by_n;  // kItemMadeBy (ProcessId)")
    e("  bool live;")
    e("};")
    e(f"inline constexpr std::array<ItemRow, {len(items)}> kItems = {{{{")
    for r in rows:
        if r is None:
            e('  {"", 0, 0, 0, 0, 0, 0, false},')
        else:
            it, p0, pn, m0, mn, mass, srt = r
            e(f'  {{{cpp_str(it.id)}, {mass}, {srt}, {p0}, {pn}, {m0}, {mn}, true}},')
    e("}};")
    e("")
    e("}  // namespace em::act::matter")
    return {OUT: "\n".join(L) + "\n", REGISTRY: reg.text()}


def main(argv=None) -> int:
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    files = build()
    if check:
        stale = [p.name for p, t in files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            sys.stderr.write(f"stale: {', '.join(stale)} -> run python3 catalogue/tools/gen_matter.py\n")
            return 1
        print("matter tables up to date")
        return 0
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
    print("écrit " + ", ".join(p.name for p in files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
