"""gen_tok2.py - generate engine/social/tokenizer/generated/tok2_gen.h from the tok-2 oracle (ai/tok2) and the catalogue.

    python3 engine/social/tokenizer/gen_tok2.py           write the header
    python3 engine/social/tokenizer/gen_tok2.py --check   exit 1 when the header is stale

One source of truth: the live tok-2 Layout (registry.json + model_interface.json). The C++ tokenizer is therefore the
same format as the oracle by construction; the parity tests prove the arithmetic. Read-only on ai/tok2.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = HERE / "generated" / "tok2_gen.h"
sys.path.insert(0, str(ROOT / "ai")); sys.path.insert(0, str(ROOT / "catalogue")); sys.path.insert(0, str(ROOT / "catalogue" / "tools"))

from tok2 import Tokenizer  # noqa: E402
from tok2.keys import FIXED_KEYS  # noqa: E402
from language import ref_targets  # noqa: E402
from schema import Catalogue  # noqa: E402

NUM_SCALES = ["bipolar10", "unipolar10", "ratio", "unit", "boolean", "qty", "qty_signed", "time", "time_until"]


def cs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num_scale(scale: str, unit: str) -> str:
    if scale == "bool":
        return "boolean"
    if scale == "qty" and unit == "°C":
        return "qty_signed"
    if scale in NUM_SCALES:
        return scale
    raise SystemExit(f"unknown numeric scale {scale}")


def generate() -> str:
    tk = Tokenizer()
    L, V = tk.layout, tk.vocab
    iface, cat = tk.interface, Catalogue.load()
    out: list[str] = []
    e = out.append
    e("// GENERATED by engine/social/tokenizer/gen_tok2.py from ai/tok2 and the catalogue - do not edit.")
    e("#pragma once")
    e('#include "emergence/social/tokenizer/tables.h"')
    e("namespace em::social::tok2::gen {")
    e(f"inline constexpr int kMaxTokens = {L.max_tokens}, kPropLen = {L.prop_len}, kNumWidth = {L.width['num']}, "
      f"kCatWidth = {L.width['cat']}, kPtrWidth = {L.width['ptr']};")
    e(f"inline constexpr std::uint64_t kInterfaceFingerprint = 0x{iface.fingerprint:016x}ull, kLayoutFingerprint = 0x{L.fingerprint:016x}ull, "
      f"kVocabFingerprint = 0x{V.fingerprint:016x}ull;")
    e(f"inline constexpr int kVocabSize = {len(V.symbols)}, kNameSlots = {V.NAME_SLOTS};")
    e(f"inline constexpr int kPadId = {V.ids[V.PAD]}, kNumId = {V.ids[V.NUM]}, kNameOtherId = {V.ids[V.NAME_OTHER]}, kName0Id = {V.ids['<name0>']};")
    e("inline constexpr const char* kPointerKinds[] = {" + ", ".join(cs(k) for k in V.POINTER_KINDS) + "};")
    e("inline constexpr int kPointerKindIds[] = {" + ", ".join(str(V.ids[k]) for k in V.POINTER_KINDS) + "};")
    e(f"inline constexpr int kNumPointerKinds = {len(V.POINTER_KINDS)};")
    e("inline constexpr std::string_view kVocabulary[] = {")
    syms = list(V.symbols)
    for i in range(0, len(syms), 8):
        e("  " + ", ".join(cs(s) for s in syms[i:i + 8]) + ",")
    e("};")
    e("inline constexpr bool kVocabIsWord[] = {" + ", ".join("true" if s in V.words else "false" for s in syms) + "};")
    # enum value / word lists, shared storage
    lists: list[list[str]] = []

    def lst(vals) -> tuple[int, int]:
        vals = list(vals or [])
        if not vals:
            return 0, 0
        for i, l in enumerate(lists):
            if l == vals:
                return i, len(vals)
        lists.append(vals)
        return len(lists) - 1, len(vals)

    tids = {n: t.type_id for n, t in L.types.items()}
    cols_txt: list[str] = []
    comps_txt: list[str] = []
    type_rows: list[str] = []
    ncols = 0
    for name, t in L.types.items():
        first = ncols
        for fname, c in t.columns.items():
            cd, sp = c.codec, c.codec.spec
            kind = cd.kind.replace("Codec", "")
            kind = {"Scalar": "scalar", "Vector": "vector", "Symbol": "symbol", "Bag": "bag", "Pointer": "pointer",
                    "PointerList": "pointer_list", "Proposition": "proposition"}[kind]
            ns = "boolean"
            if kind == "scalar":
                ns = num_scale(sp["scale"], sp.get("unit", ""))
            is_enum = sp.get("scale") == "enum" or sp.get("list_of") == "enum"
            vi, vn = lst(sp.get("values")) if is_enum else (0, 0)
            wi, wn = lst(sp.get("words"))
            rm = 0
            for rt in sp.get("ref_types") or []:
                rm |= 1 << tids[rt]
            ci, cn, multi = 0, 0, "false"
            if kind == "vector":
                multi = "true" if cd.multi else "false"
                ci, cn = len(comps_txt), len(cd.components)
                for i, (cn_, s, u, p) in enumerate(zip(cd.components, cd.scales, cd.units, cd.pools)):
                    comps_txt.append(f"  Component{{{cs(cn_)}, NumScale::{num_scale(s, u)}, {cd.cols[i]}, {'true' if p == 'sum' else 'false'}}},")
            utter = "true" if kind == "proposition" and f"{name}.{fname}" in ("REQUEST.prop", "PLAN.says") else "false"
            cols_txt.append(f"  ColumnDef{{{cs(fname)}, Codec::{kind}, NumScale::{ns}, {c.col}, {cd.width}, {'true' if is_enum else 'false'}, "
                            f"{multi}, {utter}, 0x{rm:x}u, {vi}, {vn}, {wi}, {wn}, {ci}, {cn}}},")
            ncols += 1
        fixed = "true" if t.key in FIXED_KEYS else "false"
        type_rows.append(f"  TypeDef{{{cs(name)}, {t.type_id}, {t.count}, {cs(t.key)}, {fixed}, {first}, {ncols - first}}},")
    e("inline constexpr std::string_view kStrings[] = {")
    for l in lists:
        e("  " + ", ".join(cs(s) for s in l) + ",")
    e("};")
    offs, o = [], 0
    for l in lists:
        offs.append(o); o += len(l)
    e("inline constexpr int kStringStart[] = {" + ", ".join(map(str, offs)) + "};")
    e(f"inline constexpr Component kComponents[] = {{\n" + "\n".join(comps_txt) + "\n};")
    e(f"inline constexpr ColumnDef kColumns[] = {{\n" + "\n".join(cols_txt) + "\n};")
    e(f"inline constexpr int kNumTypes = {len(L.types)}, kMaxTypeId = {max(tids.values())};")
    e("inline constexpr TypeDef kTypes[] = {\n" + "\n".join(type_rows) + "\n};")
    e("inline constexpr int kTypeId[] = {" + ", ".join(str(tids[n]) for n in L.types) + "};")
    # ---- feasibility mask tables
    sample = {t.type_id: (t.key if t.key in FIXED_KEYS else t.key + "1") for t in L.types.values()}
    classes = {}
    for tid, key in sample.items():
        try:
            classes[tid] = set(ref_targets(key, tk.grammar.vocab if hasattr(tk, "grammar") else tk.props.grammar.vocab))
        except Exception:  # noqa: BLE001
            classes[tid] = set()
    acts = cat.entries["action"]
    objcol = {}
    for tn in ("THING", "INV"):
        col = L.types[tn].columns["props"]
        objcol[tn] = {c: col.codec.cols[i] for i, c in enumerate(col.codec.components)}
    grows = []
    import json
    mi = json.loads((ROOT / "catalogue" / "generated" / "model_interface.json").read_text(encoding="utf-8"))
    for gname in iface.gestures:
        gd = mi["output"]["gestures"][gname]
        a = acts[gname]
        refs = []
        for p in gd["params"]:
            if "pointer" not in p:
                continue
            acc = set(p["pointer"])
            mask = 0
            for tid, cl in classes.items():
                if cl & acc:
                    mask |= 1 << tid
            req = a.requires.get(p["name"])
            rc = [objcol["THING"].get(req, -1), objcol["INV"].get(req, -1)] if req else [-1, -1]
            party = "true" if p["name"] in gd["party_params"] else "false"
            refs.append(f"RefParamDef{{{cs(p['name'])}, {'true' if p['optional'] else 'false'}, {'true' if 'direction' in acc else 'false'}, "
                        f"{'true' if 'form' in acc else 'false'}, {party}, 0x{mask:x}u, {rc[0]}, {rc[1]}}}")
        grows.append(f"  GestureMaskDef{{{cs(gname)}, {'true' if gd['contact'] else 'false'}, {len(refs)}, "
                     f"{{{', '.join(refs) if refs else 'RefParamDef{}'}}}}},")
    e(f"inline constexpr int kNumGestures = {len(iface.gestures)};")
    e("inline constexpr GestureMaskDef kGestureMasks[] = {\n" + "\n".join(grows) + "\n};")
    vs = cat.entries["variable"]
    tokened = sorted(v.id for v in vs.values() if v.token and v.visibility != "engine")
    engine = sorted(v.id for v in vs.values() if v.visibility == "engine")
    e("// The TokenView: the only NPC variables a module of the tokenizer may read (those with a token in the catalogue).")
    e(f"inline constexpr std::string_view kTokenVars[] = {{\n  " + ", ".join(cs(x) for x in tokened) + "\n};")
    e("// Objective variables (visibility = engine): never read, never copied into a dossier.")
    e(f"inline constexpr std::string_view kEngineVars[] = {{\n  " + ", ".join(cs(x) for x in engine) + "\n};")
    e("}  // namespace em::social::tok2::gen")
    return "\n".join(out) + "\n"


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.stderr.write("tok2_gen.h is stale: run python3 engine/social/tokenizer/gen_tok2.py\n")
            return 1
        print("tok2_gen.h up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"written {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
